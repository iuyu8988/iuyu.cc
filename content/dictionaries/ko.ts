/**
 * 사전 타입. `as const` 를 쓰면 문자열이 리터럴로 고정되어
 * 다른 언어 사전에서 값이 할당되지 않으므로, 깊은 readonly 로 완화합니다.
 */
type DeepMutable<T> = T extends readonly (infer U)[]
  ? readonly DeepMutable<U>[]
  : T extends object
    ? { readonly [K in keyof T]: DeepMutable<T[K]> }
    : T;

export type Dictionary = DeepMutable<typeof ko>;
